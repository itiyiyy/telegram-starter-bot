export function registerCommands(bot) {
  bot.command("start", async (ctx) => {
    await ctx.reply(
      "Здравствуйте! 👋 Я помощник по вопросам недвижимости.\n\nВыберите, что вас интересует:",
      { reply_markup: mainMenu }
    )
  })

  bot.command("help", (ctx) =>
    ctx.reply("Выберите нужный раздел в меню ниже или отправьте /start.")
  )

  bot.hears("🏠 Главное меню", async (ctx) => {
    await ctx.reply("Выберите интересующий раздел:", {
      reply_markup: mainMenu
    })
  })

  bot.hears("Продажа недвижимости", async (ctx) => {
    await ctx.reply(
      "🏠 Продажа недвижимости\n\nЧто вы хотите узнать?",
      { reply_markup: saleMenu }
    )
  })

  bot.hears("Какие риски могут быть в документах", async (ctx) => {
    await ctx.reply(
      "📋 Выберите ситуацию, которая относится к вашей квартире:",
      { reply_markup: docsMenu }
    )
  })

  bot.hears("⬅️ Назад к продаже", async (ctx) => {
    await ctx.reply("Раздел продажи недвижимости:", {
      reply_markup: saleMenu
    })
  })

  bot.hears("Почему я не могу продать квартиру", (ctx) =>
    ctx.reply(
      "Причин может быть несколько: не все документы готовы, есть обременение, не урегулированы права совладельцев или супругов, не выделены детские доли либо цена не соответствует рынку.\n\nНачните с проверки документов, ограничений и цены предложения.",
      { reply_markup: saleMenu }
    )
  )

  bot.hears("Зачем мне нужен риелтор", (ctx) =>
    ctx.reply(
      "Риелтор может помочь оценить рыночную цену, организовать показы, подготовить процесс сделки и скоординировать участников. Решение о сотрудничестве остаётся за вами: многое можно сделать самостоятельно, если вы понимаете этапы и риски.",
      { reply_markup: saleMenu }
    )
  )

  for (const [topic, answer] of Object.entries(answers)) {
    bot.hears(topic, (ctx) =>
      ctx.reply(
        answer + "\n\nЭто общая информация: точный порядок зависит от документов и обстоятельств. При сомнениях обратитесь к профильному юристу.",
        { reply_markup: docsMenu }
      )
    )
  }

  const otherSections = {
    "Покупка недвижимости":
      "При покупке проверьте собственника, выписку из ЕГРН, основания приобретения, обременения, зарегистрированных жильцов и условия расчётов.",
    "Сдача в аренду":
      "Перед сдачей подготовьте договор, согласуйте размер платы, залог, коммунальные платежи, срок аренды и порядок возврата квартиры.",
    "Аренда жилья":
      "Перед арендой проверьте документы арендодателя, состояние квартиры, условия договора, залог и порядок оплаты. Не переводите деньги до проверки права сдавать жильё.",
    "Покупка новостройки":
      "При покупке новостройки изучите застройщика, проектную декларацию, договор, сроки передачи квартиры и условия расчётов. Учитывайте, что конкретная проверка зависит от проекта.",
    "Ипотека":
      "Перед оформлением ипотеки сравните полную стоимость кредита, первоначальный взнос, страхование, условия досрочного погашения и ежемесячный платёж.",
    "ОСАГО":
      "ОСАГО — обязательное страхование гражданской ответственности владельца автомобиля. Проверяйте срок полиса, данные водителей и автомобиля.",
    "КАСКО":
      "КАСКО — добровольное страхование автомобиля. Сравните страховые риски, исключения, франшизу, порядок ремонта и условия выплаты."
  }

  for (const [topic, answer] of Object.entries(otherSections)) {
    bot.hears(topic, (ctx) =>
      ctx.reply(answer, { reply_markup: mainMenu })
    )
  }

  bot.on("message:text", (ctx) =>
    ctx.reply(
      "Выберите подходящий раздел с помощью кнопок меню ниже или отправьте /start.",
      { reply_markup: mainMenu }
    )
  )
}
